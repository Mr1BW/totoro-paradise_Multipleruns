def main():
    """
    CLI entry point.
    
    Reads command-line arguments, loads route data and credentials,
    then calls submit_run() to perform the full submission.
    
    Credential priority (highest first):
    1. --token / --stu-number command line args
    2. session.json file (--config)
    """
    parser = argparse.ArgumentParser(
        description='Submit run record to Totoro official API',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
    # Use session.json (default)
    python submit_run.py --route-file route.json

    # Override token
    python submit_run.py --route-file route.json --token "APPx..."

    # Full manual credentials
    python submit_run.py --route-file route.json \\
        --token "APPx..." --stu-number "162320316" --school-id "98765"
        """
    )
    parser.add_argument('--route-file', type=str, default='route.json',
                        help='Route JSON file generated by route.py (default: route.json)')
    parser.add_argument('--config', type=str, default='session.json',
                        help='Credentials file containing session.token, session.stuNumber, etc. (default: session.json)')
    parser.add_argument('--token', type=str, default='',
                        help='Override: Totoro login token')
    parser.add_argument('--stu-number', type=str, default='',
                        help='Override: Student number')
    parser.add_argument('--school-id', type=str, default='',
                        help='Override: School ID')
    parser.add_argument('--campus-id', type=str, default='',
                        help='Override: Campus ID')
    args = parser.parse_args()

    # Check RSA library availability
    try:
        import rsa
    except ImportError:
        try:
            import cryptography
        except ImportError:
            print("[ERR] RSA library not found. Install with: pip install rsa")
            sys.exit(1)

    # Load route data from generated file
    print(f"Loading route: {args.route_file}")
    with open(args.route_file, 'r', encoding='utf-8') as f:
        route_data = json.load(f)

    # Load credentials from config file
    creds = {}
    if Path(args.config).exists():
        with open(args.config, 'r', encoding='utf-8') as f:
            data = json.load(f)
        creds = data.get('session', {})

    # Resolve final credentials (CLI args override config file)
    token = args.token or creds.get('token', '')
    stu_number = args.stu_number or creds.get('stuNumber', '')
    school_id = args.school_id or creds.get('schoolId', '')
    campus_id = args.campus_id or creds.get('campusId', '')

    if not token or not stu_number:
        print("[ERR] Missing token or stuNumber")
        print("Provide via --config session.json or --token/--stu-number")
        sys.exit(1)

    print(f"stuNumber: {stu_number}")
    print(f"schoolId: {school_id}")
    print(f"campusId: {campus_id}")

    ok = submit_run(route_data, token, stu_number, school_id, campus_id)
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
