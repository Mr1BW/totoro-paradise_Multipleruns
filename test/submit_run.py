def parse_response(resp_text: str) -> dict:
    """
    Parse server response, attempting RSA decryption if needed.
    
    Server responses come in two forms:
    1. Plain JSON (rare): {"code":"0", "scantronId":"xxx"}
    2. Encrypted Base64 (common): "U9Xx7vK2mP..."
    
    This function tries both approaches.
    
    Args:
        resp_text: Raw response body from server
        
    Returns:
        Parsed dict from decrypted or plain JSON
    """
    if not resp_text:
        return {}
    
    # Try plain JSON first
    try:
        return json.loads(resp_text)
    except json.JSONDecodeError:
        pass
    
    # Try RSA decryption (response is base64-encoded encrypted string)
    try:
        decrypted = rsa_decrypt(resp_text)
        return json.loads(decrypted)
    except Exception:
        # If decryption fails too, return as-is for debugging
        return {"raw_response": resp_text[:200]}


def post_encrypted(endpoint: str, payload: dict, sess: requests.Session) -> dict:
    """
    Send RSA-encrypted POST request to official API.
    
    Request flow:
        dict payload -> JSON string -> RSA encrypt -> Base64 -> HTTP POST
    
    Response flow:
        HTTP body -> Base64 decode -> RSA decrypt -> JSON parse -> dict
    
    Used for APIs: getRunBegin, sunRunExercises, login, getSunRunPaper, etc.
    
    Args:
        endpoint: API path (e.g. 'sunrun/getRunBegin')
        payload: Plaintext dict to send
        sess: requests Session object with headers
        
    Returns:
        Decrypted response dict from server
    """
    encrypted = rsa_encrypt(json.dumps(payload))
    url = f"{BASE_URL}/{endpoint}"
    
    print(f"\n[POST] {url}")
    print(f"[BODY] {json.dumps(payload, ensure_ascii=False)}")
    
    resp = sess.post(url, data=encrypted, verify=False, timeout=15)
    resp.raise_for_status()
    
    result = parse_response(resp.text)
    print(f"[RESP] {json.dumps(result, ensure_ascii=False)[:300]}")
    return result


def post_json(endpoint: str, payload: dict, sess: requests.Session) -> dict:
    """
    Send plaintext JSON POST request to official API.
    
    Unlike post_encrypted(), this sends raw JSON without RSA encryption.
    Used only for: sunRunExercisesDetail (GPS track submission).
    
    Args:
        endpoint: API path (e.g. 'platform/recrecord/sunRunExercisesDetail')
        payload: Plaintext dict to send
        sess: requests Session object with headers
        
    Returns:
        Response dict from server (usually plain JSON for this endpoint)
    """
    url = f"{BASE_URL}/{endpoint}"
    
    print(f"\n[POST] {url}")
    print(f"[BODY] {json.dumps(payload, ensure_ascii=False)[:120]}...")
    
    resp = sess.post(url, json=payload, headers={'Content-Type': 'application/json'},
                     verify=False, timeout=15)
    resp.raise_for_status()
    
    result = parse_response(resp.text)
    print(f"[RESP] {json.dumps(result, ensure_ascii=False)[:300]}")
    return result


