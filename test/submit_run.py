def rsa_encrypt(data: str) -> str:
    """
    Encrypt plaintext JSON string using RSA public key (PKCS#1) with chunking.
    
    RSA keys have a maximum message size (key_length - 11 bytes for PKCS#1).
    For a 1024-bit key, this is 117 bytes. Longer messages must be split
    into chunks, encrypted separately, and concatenated.
    
    The server decrypts by splitting the ciphertext into key-length chunks
    and decrypting each one, then concatenating the plaintext.
    
    Args:
        data: Plaintext JSON string to encrypt
        
    Returns:
        Base64-encoded RSA ciphertext (may contain multiple encrypted chunks)
    """
    data_bytes = data.encode('utf-8')
    
    try:
        import rsa
        pub_key = rsa.PublicKey.load_pkcs1_openssl_pem(PUBLIC_KEY_PEM.encode())
        keylength = rsa.common.byte_size(pub_key.n)
        max_chunk = keylength - 11  # PKCS#1 v1.5 padding overhead
        
        encrypted_chunks = []
        for i in range(0, len(data_bytes), max_chunk):
            chunk = data_bytes[i:i + max_chunk]
            encrypted = rsa.encrypt(chunk, pub_key)
            encrypted_chunks.append(encrypted)
        
        return base64.b64encode(b''.join(encrypted_chunks)).decode('utf-8')
        
    except ImportError:
        from cryptography.hazmat.primitives import serialization
        from cryptography.hazmat.primitives.asymmetric import padding
        pub_key = serialization.load_pem_public_key(PUBLIC_KEY_PEM.encode())
        encrypted = pub_key.encrypt(data_bytes, padding.PKCS1v15())
        return base64.b64encode(encrypted).decode('utf-8')


def rsa_decrypt(data: str) -> str:
    """
    Decrypt Base64-encoded RSA ciphertext using private key (PKCS#1) with chunking.
    
    Handles both single-chunk and multi-chunk ciphertexts.
    Multi-chunk format is produced when the original message exceeded
    the RSA key's maximum message size.
    
    Args:
        data: Base64-encoded RSA ciphertext from server
        
    Returns:
        Decrypted plaintext JSON string
    """
    encrypted_data = base64.b64decode(data)
    
    try:
        import rsa
        priv_key = rsa.PrivateKey.load_pkcs1(PRIVATE_KEY_PEM.encode(), format='PEM')
        keylength = rsa.common.byte_size(priv_key.n)
        
        decrypted_chunks = []
        for i in range(0, len(encrypted_data), keylength):
            chunk = encrypted_data[i:i + keylength]
            decrypted = rsa.decrypt(chunk, priv_key)
            decrypted_chunks.append(decrypted)
        
        return b''.join(decrypted_chunks).decode('utf-8')
        
    except ImportError:
        from cryptography.hazmat.primitives import serialization
        from cryptography.hazmat.primitives.asymmetric import padding
        priv_key = serialization.load_pem_private_key(PRIVATE_KEY_PEM.encode(), password=None)
        decrypted = priv_key.decrypt(encrypted_data, padding.PKCS1v15())
        return decrypted.decode('utf-8')


