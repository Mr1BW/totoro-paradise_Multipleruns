def generate_mac(stu_number: str) -> str:
    """
    Generate device MAC address from student number.
    
    Format: XX:XX:XX:XX:XX:XX (6 pairs of hex digits separated by colons)
    Example: "17:b0:2b:f2:81:8c"
    
    Based on totoroschool API documentation, MAC should be in standard
    hardware address format with colons, not a plain hex string.
    
    Args:
        stu_number: Student ID string
        
    Returns:
        Standard MAC address string (17 chars with colons)
    """
    hash_hex = hashlib.sha256(stu_number.encode()).hexdigest()[:12]
    return ':'.join(hash_hex[i:i+2] for i in range(0, 12, 2))


