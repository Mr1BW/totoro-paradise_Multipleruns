def submit_run(route_data: dict, token: str, stu_number: str, school_id: str, campus_id: str) -> bool:
    """
    Complete run submission workflow.
    
    Sends 3 API calls in sequence:
    1. getRunBegin: Notify server that run has started
    2. sunRunExercises: Submit run summary (time, distance, speed, steps, MAC)
    3. sunRunExercisesDetail: Submit GPS track coordinates
    
    Args:
        route_data: Dict from route.json containing:
            - mockRoute: List of GPS coordinates
            - startTime, endTime, usedTime: Time info
            - avgSpeed, targetDistance: Performance metrics
            - routeInfo: {taskId, pointId, pointName}
        token: Login token from session.json
        stu_number: Student number
        school_id: School ID
        campus_id: Campus ID
        
    Returns:
        True if all steps succeed, False otherwise
    """
    sess = requests.Session()
    sess.headers.update({
        'User-Agent': 'TotoroSchool/1.2.14 (iPhone; iOS 17.4.1; Scale/3.00)',
        'Content-Type': 'application/json; charset=utf-8',
        'Accept': 'application/json',
        'Accept-Encoding': 'gzip, deflate, br',
        'Connection': 'keep-alive',
        'Host': 'app.xtotoro.com',
    })

    print("=" * 60)
    print("Totoro Run Submission (Official API)")
    print("=" * 60)
    print(f"Route: {route_data['routeInfo']['pointName']}")
    print(f"Distance: {route_data['targetDistance']} km")
    print(f"Time: {route_data['startTime']} ~ {route_data['endTime']}")
    print(f"Duration: {route_data['usedTime']}")
    print(f"Speed: {route_data['avgSpeed']} km/h")
    print(f"Track: {route_data['pointCount']} points")

    # -------------------------------------------------------------------------
    # Step 1: getRunBegin
    # Purpose: Notify server that user has started running.
    # Payload: Basic user info (token, stuNumber, schoolId)
    # Response: Generic success message (no critical data)
    # -------------------------------------------------------------------------
    print("\n--- Step 1: getRunBegin ---")
    try:
        post_encrypted('sunrun/getRunBegin', {
            "campusId": campus_id,
            "schoolId": school_id,
            "stuNumber": stu_number,
            "token": token
        }, sess)
        print("OK")
    except Exception as e:
        print(f"WARN: {e}")

    # -------------------------------------------------------------------------
    # Step 2: sunRunExercises (Summary)
    # Purpose: Submit all run metadata (the "report card").
    # Payload: time, distance, speed, steps, device info, MAC, etc.
    # Response: {scantronId: "xxx"} — needed for Step 3
    # Note: pointList field is empty string here, track goes in Step 3
    # -------------------------------------------------------------------------
    print("\n--- Step 2: sunRunExercises (Summary) ---")
    summary = {
        "LocalSubmitReason": "",
        "avgSpeed": route_data['avgSpeed'],
        "baseStation": "",
        "endTime": route_data['endTime'],
        "evaluateDate": route_data['evaluateDate'],
        "fitDegree": "1",
        "flag": "1",
        "headImage": "",
        "ifLocalSubmit": "1",
        "km": route_data['targetDistance'],
        "mac": generate_mac(stu_number),
        "phoneInfo": "$CN11/iPhone15,4/17.4.1",
        "phoneNumber": "",
        "pointList": "",
        "routeId": route_data['routeInfo']['pointId'],
        "runType": "0",
        "sensorString": "",
        "startTime": route_data['startTime'],
        "steps": route_data['steps'],
        "stuNumber": stu_number,
        "taskId": route_data['routeInfo']['taskId'],
        "token": token,
        "usedTime": route_data['usedTime'],
        "version": "1.2.14",
        "warnFlag": "0",
        "warnType": "",
        "faceData": ""
    }
    result = post_encrypted('platform/recrecord/sunRunExercises', summary, sess)
    scantron_id = result.get('scantronId')
    if not scantron_id:
        print(f"FAIL: no scantronId: {result}")
        return False
    print(f"OK: scantronId={scantron_id}")

    # -------------------------------------------------------------------------
    # Step 3: sunRunExercisesDetail (GPS Track)
    # Purpose: Submit actual GPS coordinates.
    # Payload: pointList (array of {longitude, latitude}), scantronId
    # Note: Sent as PLAIN JSON (not encrypted)
    # Response: Generic success
    # -------------------------------------------------------------------------
    print("\n--- Step 3: sunRunExercisesDetail (Track) ---")
    track = {
        "pointList": route_data['mockRoute'],
        "scantronId": scantron_id,
        "stuNumber": stu_number,
        "token": token
    }
    post_json('platform/recrecord/sunRunExercisesDetail', track, sess)
    print(f"OK: {len(route_data['mockRoute'])} points sent")

    print("\n" + "=" * 60)
    print("DONE")
    print("=" * 60)
    return True


